void vga_putchar(int x, int y, char c, uint8_t color) {
    int idx = -1;
    if (c >= 'A' && c <= 'Z') idx = c - 'A';
    else if (c >= '0' && c <= '9') idx = 26 + (c - '0');

    if (idx == -1) return;
    for (int i = 0; i < 8; i++) {
        for (int j = 0; j < 8; j++) {
            // FIX: un-mirrors the letters
            if (font[idx][i] & (1 << (7 - j))) vga_plot(x + j, y + i, color);
        }
    }
}

